function money(halalas, lang) {
  const n = (halalas || 0) / 100;
  const whole = Number.isInteger(n);
  const s = n.toLocaleString('en-US', { minimumFractionDigits: whole ? 0 : 2, maximumFractionDigits: 2 });
  return lang === 'ar' ? `${s} ر.س` : `SAR ${s}`;
}

const pick = (obj, field, lang) => obj[`${field}_${lang}`] || obj[`${field}_en`] || '';

